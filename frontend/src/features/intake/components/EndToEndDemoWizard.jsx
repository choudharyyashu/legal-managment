import React, { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import {
  Sparkles,
  UserPlus,
  ShieldCheck,
  FileText,
  FileCheck,
  CheckCircle2,
  Briefcase,
  Users,
  Calendar,
  ArrowRight,
  ArrowLeft,
  Clock,
  ExternalLink
} from 'lucide-react';
import { Button } from '../../../components/ui/Button';
import { Modal } from '../../../components/ui/Modal';
import { useToast } from '../../../components/ui/Toast';
import { useClients } from '../../../context/ClientContext';
import { useMatters } from '../../../context/MatterContext';
import { useTasks } from '../../../context/TaskContext';
import { useAuth } from '../../../hooks/useAuth';

export function EndToEndDemoWizard({ isOpen, onClose }) {
  const navigate = useNavigate();
  const { currentUser } = useAuth();
  const { addToast } = useToast();
  const { addClient, addIntake } = useClients();
  const { addMatter } = useMatters();
  const { addTask } = useTasks();

  const [currentStep, setCurrentStep] = useState(1);
  const totalSteps = 6;

  // Wizard Data State
  const [demoData, setDemoData] = useState({
    clientName: 'Wasatch CleanTech Solutions Inc.',
    contactPerson: 'Dr. Arthur Vance (CEO)',
    email: 'avance@wasatchcleantech.com',
    phone: '(801) 555-0899',
    practiceAreaId: 'pa-1',
    practiceAreaName: 'Civil Litigation & Dispute Resolution',
    adverseParty: 'Intermountain BioEnergy Corp',
    matterTitle: 'Wasatch CleanTech Solutions v. Intermountain BioEnergy (Patent License Breach)',
    hourlyRate: 500,
    retainerAmount: 7500,
    conflictStatus: 'Cleared',
    signatureStatus: 'Drafted',
    createdClientId: null,
    createdMatterId: null,
  });

  const handleSimulateSign = () => {
    setDemoData(prev => ({ ...prev, signatureStatus: 'Signed' }));
    addToast('Client signature captured for Engagement Letter.', 'success');
  };

  const handleCompleteFullWorkflow = () => {
    // 1. Create Intake Record
    const intake = addIntake({
      prospectiveClient: demoData.clientName,
      contactPerson: demoData.contactPerson,
      email: demoData.email,
      phone: demoData.phone,
      practiceAreaId: demoData.practiceAreaId,
      practiceAreaName: demoData.practiceAreaName,
      adverseParties: demoData.adverseParty,
      conflictStatus: 'Cleared',
      reviewedBy: currentUser?.name || 'Eleanor Heugly, Esq.',
      reviewedAt: new Date().toISOString().split('T')[0],
      matterSummary: demoData.matterTitle,
      convertedToClient: true,
    });

    // 2. Create Active Client
    const newClient = addClient({
      name: demoData.clientName,
      primaryContact: demoData.contactPerson,
      email: demoData.email,
      phone: demoData.phone,
      type: 'Organization',
      assignedAttorneyId: 'usr-2',
      assignedAttorneyName: 'Thomas Bludworth, Esq.',
      status: 'Active',
      notes: `Onboarded via End-to-End Legal Onboarding Workflow. Adverse check cleared against ${demoData.adverseParty}. Retainer $${demoData.retainerAmount.toLocaleString()} deposited to IOLTA.`,
    });

    // 3. Create Active Matter
    const newMatter = addMatter({
      title: demoData.matterTitle,
      clientId: newClient.id,
      clientName: newClient.name,
      practiceAreaId: demoData.practiceAreaId,
      practiceAreaName: demoData.practiceAreaName,
      status: 'Active',
      stage: 'Pleadings & Service',
      responsibleAttorneyId: 'usr-2',
      responsibleAttorneyName: 'Thomas Bludworth, Esq.',
      assignedStaffIds: ['usr-4'],
      assignedStaffNames: ['Marcus Vance'],
      billingType: 'Hourly',
      hourlyRate: demoData.hourlyRate,
      budget: 45000,
      description: 'Commercial patent licensing dispute regarding solar turbine proprietary designs.',
    });

    // 4. Spawn Initial Tasks in TaskContext
    addTask({
      title: 'Draft Complaint & Issue Summons on Registered Agent',
      matterId: newMatter.id,
      matterTitle: newMatter.title,
      clientId: newClient.id,
      clientName: newClient.name,
      assignedToId: 'usr-4',
      assignedToName: 'Marcus Vance',
      dueDate: new Date(Date.now() + 5 * 86400000).toISOString().split('T')[0],
      priority: 'Urgent',
      status: 'In Progress',
      description: 'Generated by Onboarding Workflow Engine for newly converted matter.',
    });

    addTask({
      title: 'Initial Rule 26 Case Management Conference Preparation',
      matterId: newMatter.id,
      matterTitle: newMatter.title,
      clientId: newClient.id,
      clientName: newClient.name,
      assignedToId: 'usr-2',
      assignedToName: 'Thomas Bludworth, Esq.',
      dueDate: new Date(Date.now() + 14 * 86400000).toISOString().split('T')[0],
      priority: 'High',
      status: 'Not Started',
      description: 'Pre-trial discovery scheduling and Utah Third District Court filings.',
    });

    setDemoData(prev => ({
      ...prev,
      createdClientId: newClient.id,
      createdMatterId: newMatter.id,
    }));

    addToast(
      `Complete Onboarding Executed: Client (${newClient.id}), Matter (${newMatter.id}), and initial tasks created!`,
      'success'
    );
    setCurrentStep(6);
  };

  return (
    <Modal
      isOpen={isOpen}
      onClose={onClose}
      title="Interactive End-to-End Legal Practice Management Walkthrough"
      size="xl"
    >
      <div className="space-y-4 text-xs text-[#202A35]">
        {/* Stepper Progress Indicator */}
        <div className="grid grid-cols-6 gap-1 border-b border-[#D9D6CF] pb-3">
          {[
            '1. Prospective Intake',
            '2. Conflict Check',
            '3. Engagement Letter',
            '4. Client E-Sign',
            '5. Matter Creation',
            '6. Ready & Active'
          ].map((label, idx) => {
            const stepNum = idx + 1;
            const isCompleted = stepNum < currentStep;
            const isCurrent = stepNum === currentStep;

            return (
              <div
                key={label}
                className={`p-1.5 rounded text-center transition-all ${
                  isCompleted
                    ? 'bg-emerald-50 text-emerald-800 font-semibold'
                    : isCurrent
                    ? 'bg-[#06244B] text-white font-bold'
                    : 'bg-[#FAF7F0] text-[#667085]'
                }`}
              >
                <span className="block text-[10px] leading-tight truncate">{label}</span>
              </div>
            );
          })}
        </div>

        {/* STEP 1: PROSPECTIVE INTAKE */}
        {currentStep === 1 && (
          <div className="space-y-3">
            <div className="p-3 bg-[#F5F0E5]/60 rounded border border-[#D9D6CF]">
              <h4 className="font-serif font-bold text-[#06244B] text-sm">Step 1: New Prospective Client Intake</h4>
              <p className="text-[11px] text-[#667085] mt-0.5">
                Prospective corporate client submits initial inquiry regarding a commercial patent licensing breach in Salt Lake County.
              </p>
            </div>

            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 p-3 bg-white rounded border border-[#D9D6CF]">
              <div>
                <span className="text-[10px] uppercase font-bold text-[#667085] block">Prospective Entity:</span>
                <span className="font-bold text-[#06244B]">{demoData.clientName}</span>
              </div>
              <div>
                <span className="text-[10px] uppercase font-bold text-[#667085] block">Authorized Contact:</span>
                <span>{demoData.contactPerson}</span>
              </div>
              <div>
                <span className="text-[10px] uppercase font-bold text-[#667085] block">Practice Area:</span>
                <span>{demoData.practiceAreaName}</span>
              </div>
              <div>
                <span className="text-[10px] uppercase font-bold text-[#667085] block">Adverse Party Claimed:</span>
                <span className="font-bold text-rose-700">{demoData.adverseParty}</span>
              </div>
            </div>

            <div className="flex justify-end pt-2">
              <Button size="sm" variant="primary" onClick={() => setCurrentStep(2)}>
                <span>Proceed to Conflict Check</span>
                <ArrowRight className="w-3.5 h-3.5 ml-1.5" />
              </Button>
            </div>
          </div>
        )}

        {/* STEP 2: CONFLICT SEARCH */}
        {currentStep === 2 && (
          <div className="space-y-3">
            <div className="p-3 bg-[#F5F0E5]/60 rounded border border-[#D9D6CF]">
              <h4 className="font-serif font-bold text-[#06244B] text-sm">Step 2: Utah RPC 1.7 Conflict Clearance</h4>
              <p className="text-[11px] text-[#667085] mt-0.5">
                Simulated query against firm client rosters, adverse parties, and closed files for "{demoData.adverseParty}".
              </p>
            </div>

            <div className="p-4 bg-emerald-50 rounded border border-emerald-200 space-y-2">
              <div className="flex items-center gap-2 text-emerald-900 font-bold">
                <CheckCircle2 className="w-5 h-5 text-emerald-600" />
                <span>Zero Conflict of Interest Identified</span>
              </div>
              <p className="text-[11px] text-emerald-800 leading-relaxed">
                Intermountain BioEnergy Corp does not appear as an active client, past client, or adverse party in any active litigation. Representation cleared under Utah RPC 1.7.
              </p>
              <div className="pt-2 text-[10px] font-mono text-emerald-900 border-t border-emerald-200">
                Clearance Certificate Issued: UT-RPC1.7-20261110 • Authorized by {currentUser?.name || 'Eleanor Heugly, Esq.'}
              </div>
            </div>

            <div className="flex justify-between pt-2">
              <Button size="sm" variant="outline" onClick={() => setCurrentStep(1)}>
                Back
              </Button>
              <Button size="sm" variant="primary" onClick={() => setCurrentStep(3)}>
                <span>Generate Engagement Letter</span>
                <ArrowRight className="w-3.5 h-3.5 ml-1.5" />
              </Button>
            </div>
          </div>
        )}

        {/* STEP 3: ENGAGEMENT LETTER PREVIEW */}
        {currentStep === 3 && (
          <div className="space-y-3">
            <div className="p-3 bg-[#F5F0E5]/60 rounded border border-[#D9D6CF]">
              <h4 className="font-serif font-bold text-[#06244B] text-sm">Step 3: Engagement Letter &amp; Retainer Terms</h4>
              <p className="text-[11px] text-[#667085] mt-0.5">
                Draft legal agreement generated with Utah RPC 1.5 fee disclosures and IOLTA retainer deposit requirement.
              </p>
            </div>

            <div className="p-4 bg-white rounded border border-[#D9D6CF] space-y-2 text-[11px]">
              <div className="flex justify-between border-b border-[#F5F0E5] pb-2 font-serif font-bold text-[#06244B]">
                <span>HEUGLY &amp; BLUDWORTH RETAINER AGREEMENT</span>
                <span>$500.00 / Hour</span>
              </div>
              <p><strong>Client: </strong>{demoData.clientName}</p>
              <p><strong>Matter: </strong>{demoData.matterTitle}</p>
              <p><strong>Trust Retainer Deposit: </strong>${demoData.retainerAmount.toLocaleString()}.00 (Utah Rule 14-1001 IOLTA Account)</p>
              <p className="text-[#667085] text-[10px]">
                Agreement ready for electronic signature dispatch via secure TLS delivery.
              </p>
            </div>

            <div className="flex justify-between pt-2">
              <Button size="sm" variant="outline" onClick={() => setCurrentStep(2)}>
                Back
              </Button>
              <Button size="sm" variant="primary" onClick={() => setCurrentStep(4)}>
                <span>Dispatch for E-Signature</span>
                <ArrowRight className="w-3.5 h-3.5 ml-1.5" />
              </Button>
            </div>
          </div>
        )}

        {/* STEP 4: SIGNATURE CAPTURE */}
        {currentStep === 4 && (
          <div className="space-y-3">
            <div className="p-3 bg-[#F5F0E5]/60 rounded border border-[#D9D6CF]">
              <h4 className="font-serif font-bold text-[#06244B] text-sm">Step 4: Client E-Signature Execution</h4>
              <p className="text-[11px] text-[#667085] mt-0.5">
                Document dispatched to {demoData.email}. Awaiting legal signature capture.
              </p>
            </div>

            <div className="p-4 bg-white rounded border border-[#D9D6CF] text-center space-y-3">
              <span className={`inline-block text-xs uppercase font-bold px-3 py-1 rounded border ${
                demoData.signatureStatus === 'Signed'
                  ? 'bg-emerald-100 text-emerald-800 border-emerald-300'
                  : 'bg-amber-100 text-amber-800 border-amber-300'
              }`}>
                Status: {demoData.signatureStatus === 'Signed' ? 'Legally Executed (Signed)' : 'Dispatched (Awaiting Signature)'}
              </span>

              {demoData.signatureStatus !== 'Signed' ? (
                <div className="space-y-2">
                  <p className="text-[11px] text-[#667085]">
                    Click below to simulate client Dr. Arthur Vance reviewing and executing the engagement letter.
                  </p>
                  <Button size="sm" variant="primary" onClick={handleSimulateSign} className="bg-emerald-700 hover:bg-emerald-800">
                    <CheckCircle2 className="w-3.5 h-3.5 mr-1.5" />
                    Simulate Client 1-Click Signature
                  </Button>
                </div>
              ) : (
                <div className="p-2 bg-emerald-50 rounded text-emerald-900 text-xs">
                  ✓ Signed by Dr. Arthur Vance • IP 166.70.82.14 • SHA-256 Tamper-Proof Certificate Generated.
                </div>
              )}
            </div>

            <div className="flex justify-between pt-2">
              <Button size="sm" variant="outline" onClick={() => setCurrentStep(3)}>
                Back
              </Button>
              <Button
                size="sm"
                variant="primary"
                disabled={demoData.signatureStatus !== 'Signed'}
                onClick={handleCompleteFullWorkflow}
                className={demoData.signatureStatus === 'Signed' ? '' : 'opacity-50 cursor-not-allowed'}
              >
                <span>Convert to Active Client &amp; Open Matter</span>
                <ArrowRight className="w-3.5 h-3.5 ml-1.5" />
              </Button>
            </div>
          </div>
        )}

        {/* STEP 6: COMPLETED & ACTIVE WORKFLOW SUMMARY */}
        {currentStep === 6 && (
          <div className="space-y-4">
            <div className="p-4 bg-emerald-50 rounded border border-emerald-200 text-center space-y-1">
              <CheckCircle2 className="w-10 h-10 text-emerald-600 mx-auto" />
              <h4 className="font-serif font-bold text-base text-emerald-950">
                End-to-End Legal Onboarding Successfully Executed!
              </h4>
              <p className="text-xs text-emerald-800 max-w-md mx-auto">
                The entire connected workflow from Prospective Intake to Active Docket is complete and updated across the frontend state.
              </p>
            </div>

            <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 text-xs">
              <div className="p-3 bg-white rounded border border-[#D9D6CF] space-y-1">
                <span className="font-bold text-[#06244B] flex items-center gap-1.5">
                  <UserPlus className="w-3.5 h-3.5 text-[#A4432B]" />
                  <span>New Client Active Record:</span>
                </span>
                <p className="text-[#06244B] font-semibold">{demoData.clientName}</p>
                <p className="text-[#667085] text-[11px]">ID: {demoData.createdClientId || 'CLI-1008'} • Status: Active</p>
              </div>

              <div className="p-3 bg-white rounded border border-[#D9D6CF] space-y-1">
                <span className="font-bold text-[#06244B] flex items-center gap-1.5">
                  <Briefcase className="w-3.5 h-3.5 text-[#A4432B]" />
                  <span>New Active Matter Docket:</span>
                </span>
                <p className="text-[#06244B] font-semibold truncate">{demoData.matterTitle}</p>
                <p className="text-[#667085] text-[11px]">ID: {demoData.createdMatterId || 'MAT-2026-0801'} • Stage: Pleadings &amp; Service</p>
              </div>
            </div>

            <div className="p-3 bg-[#F5F0E5]/60 rounded border border-[#D9D6CF] text-xs space-y-1">
              <span className="font-bold text-[#06244B] block">Initial Workflow Actions Synchronized:</span>
              <ul className="list-disc pl-4 space-y-0.5 text-[11px] text-[#667085]">
                <li>Task spawned: <strong>"Draft Complaint &amp; Issue Summons"</strong> assigned to Marcus Vance (Paralegal)</li>
                <li>Task spawned: <strong>"Initial Rule 26 Conference Prep"</strong> assigned to Thomas Bludworth (Attorney)</li>
                <li>$7,500.00 IOLTA trust retainer logged to matter ledger</li>
              </ul>
            </div>

            <div className="flex items-center justify-between pt-2 border-t border-[#D9D6CF]">
              <Button size="sm" variant="outline" onClick={onClose}>
                Done
              </Button>

              <div className="flex items-center gap-2">
                <Button
                  size="sm"
                  variant="primary"
                  onClick={() => {
                    onClose();
                    navigate(`/matters/${demoData.createdMatterId || 'MAT-2025-0101'}`);
                  }}
                >
                  <Briefcase className="w-3.5 h-3.5 mr-1.5" />
                  View New Matter Docket
                </Button>
              </div>
            </div>
          </div>
        )}
      </div>
    </Modal>
  );
}

